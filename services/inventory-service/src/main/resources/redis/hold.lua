-- Holds 1..N seats of one event for one user, all or nothing (README section 9.2).
--
-- Redis runs a script to completion before anything else, which is what makes the check and the
-- change one step: two users asking for the same seat at the same millisecond are serialised here,
-- and the loser sees the seat as taken rather than taking it as well. This is layer 1 of the two
-- layers against overselling; layer 2 is the primary key of seat_sale.
--
-- Everything this script touches belongs to one event and shares its hash tag, so the whole script
-- runs on one slot and stays valid on a Redis Cluster.
--
-- KEYS[1] seats hash            seatId -> A | H:<holdId> | S
-- KEYS[2] seat state version    monotonic counter of the seat map
-- KEYS[3] available counter     seats that can still be taken
-- KEYS[4] expiry sorted set     ACTIVE holdId scored by expiresAt
-- KEYS[5] userhold              the active hold of this user for this event
-- KEYS[6] idempotency           the stored answer of this (user, key) pair
-- KEYS[7] hold hash             the hold itself
-- KEYS[8] seat events stream    what the relay forwards to Kafka
--
-- ARGV[1] holdId                generated by the service, so it is known before this runs
-- ARGV[2] userId
-- ARGV[3] expiresAt             epoch millis
-- ARGV[4] now                   epoch millis, from the injected clock
-- ARGV[5] idempotency ttl       seconds
-- ARGV[6] hold ttl              seconds
-- ARGV[7] userhold ttl          millis, relative, because a Redis TTL is wall clock while the
--                               service reads an injected clock, and the two may disagree
-- ARGV[8] stream maxlen
-- ARGV[9] eventId
-- ARGV[10] request fingerprint  what the same idempotency key has to carry to be the same request
-- ARGV[11..] seatIds
--
-- Returns a JSON object whose status is OK, CONFLICT, HOLD_LIMIT, UNKNOWN_SEAT or
-- IDEMPOTENCY_KEY_REUSED.

local seats_key = KEYS[1]
local version_key = KEYS[2]
local available_key = KEYS[3]
local expiry_key = KEYS[4]
local userhold_key = KEYS[5]
local idempotency_key = KEYS[6]
local hold_key = KEYS[7]
local stream_key = KEYS[8]

local hold_id = ARGV[1]
local user_id = ARGV[2]
local expires_at = tonumber(ARGV[3])
local now = tonumber(ARGV[4])
local idempotency_ttl = tonumber(ARGV[5])
local hold_ttl = tonumber(ARGV[6])
local userhold_ttl = tonumber(ARGV[7])
local stream_maxlen = ARGV[8]
local event_id = ARGV[9]
local fingerprint = ARGV[10]

local seat_ids = {}
for i = 11, #ARGV do
  seat_ids[#seat_ids + 1] = ARGV[i]
end

-- A repeat of a request that already happened: the stored answer, not a second hold.
local stored = redis.call('GET', idempotency_key)
if stored then
  local record = cjson.decode(stored)
  if record.fingerprint ~= fingerprint then
    -- Same key, different seats: the client is confused, and guessing which one it meant
    -- would be worse than refusing (README section 9.4).
    return cjson.encode({ status = 'IDEMPOTENCY_KEY_REUSED' })
  end
  return cjson.encode(record.response)
end

-- One active hold per user per event, invariant I8.
local existing_hold = redis.call('GET', userhold_key)
if existing_hold then
  return cjson.encode({ status = 'HOLD_LIMIT', holdId = existing_hold })
end

-- Two passes, because the two answers mean different things: a seat this event does not have is a
-- bad request, while a seat somebody else holds is a lost race.
local unknown = {}
local conflicting = {}
for i = 1, #seat_ids do
  local state = redis.call('HGET', seats_key, seat_ids[i])
  if not state then
    unknown[#unknown + 1] = seat_ids[i]
  elseif state ~= 'A' then
    conflicting[#conflicting + 1] = seat_ids[i]
  end
end
if #unknown > 0 then
  return cjson.encode({ status = 'UNKNOWN_SEAT', unknownSeatIds = unknown })
end
if #conflicting > 0 then
  return cjson.encode({ status = 'CONFLICT', conflictingSeatIds = conflicting })
end

local held_value = 'H:' .. hold_id
for i = 1, #seat_ids do
  redis.call('HSET', seats_key, seat_ids[i], held_value)
end
redis.call('DECRBY', available_key, #seat_ids)

local seats_csv = table.concat(seat_ids, ',')
redis.call('HSET', hold_key,
  'userId', user_id,
  'eventId', event_id,
  'seats', seats_csv,
  'expiresAt', expires_at,
  'status', 'ACTIVE')
-- The hold outlives its own expiry on purpose: a client that comes back late reads why it lost
-- the seats instead of a 404, and the SAGA can still look it up.
redis.call('EXPIRE', hold_key, hold_ttl)

redis.call('ZADD', expiry_key, expires_at, hold_id)
-- The sweeper and the release both clear this key. The TTL is only a safety net for the case
-- where neither ever runs, so that a crash cannot lock a user out of an event for good. It is
-- relative, so it means the same thing whatever instant the service clock is at.
redis.call('SET', userhold_key, hold_id, 'PX', userhold_ttl)

local version = redis.call('INCR', version_key)
redis.call('XADD', stream_key, 'MAXLEN', '~', stream_maxlen, '*',
  'type', 'SeatsHeld',
  'eventId', event_id,
  'holdId', hold_id,
  'seats', seats_csv,
  'version', version,
  'occurredAt', now)

local response = {
  status = 'OK',
  holdId = hold_id,
  version = version,
  expiresAt = expires_at,
  seatIds = seat_ids
}
-- Only a hold that happened is remembered: a client that retries after a conflict is asking a
-- question whose answer may have changed, and should get the new one.
redis.call('SET', idempotency_key,
  cjson.encode({ fingerprint = fingerprint, response = response }),
  'EX', idempotency_ttl)

return cjson.encode(response)
